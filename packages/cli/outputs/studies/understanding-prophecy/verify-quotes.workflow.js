// `args` may be an array of slugs (or slug-prefixes like "14") to verify a
// subset; if omitted, verify all. Recompile only runs when verifying the full set.
const onlySlugs = Array.isArray(args) && args.length > 0 ? args.map(String) : null;
const SECTIONS = onlySlugs
  ? ALL_SECTIONS.filter(([slug]) =>
      onlySlugs.some((a) => slug === a || slug.startsWith(a + '-') || slug.startsWith(a)),
    )
  : ALL_SECTIONS;
const RECOMPILE = !onlySlugs;

const VERIFY_RECIPE = `
## What you are verifying

Each pioneer/EGW source quote in this file looks like:
\`\`\`
    > "<quoted sentence(s) from the source>" — DAR 192.
\`\`\`
(A 4-space-indented Markdown blockquote, ending with an em-dash + the refcode.)

These were machine-generated by quoting from \`egw lookup\`. MOST are correct and verbatim. A MINORITY have defects you must catch and fix:
- **Wrong refcode** — the quote is real but the page number is off (e.g. attributed to GEP 15 when the sentence is actually on GEP 34).
- **Paraphrase masquerading as a quote** — the words were altered/embellished, not copied verbatim (e.g. inserting "(his four leading generals)" or changing "did not constitute another kingdom" into "did not conquer his empire").
- **Quote doesn't support the bullet** — rare, but a mismatched paragraph.

## How to verify each quote (do this for EVERY \`>\` quote block in the file)

1. Read the refcode (e.g. \`DAR 192\`, \`GC 326.2\`, \`GEP 34.4\`, \`TRMC 4\`, \`GC 549-550\`).
2. Run \`bun run packages/cli/src/main.ts egw lookup "<refcode>" --json\` and read \`.paragraphs[].text\`.
   - For a page RANGE (\`GC 549-550\`), look up each page (\`GC 549\`, then \`GC 550\`).
   - For a bare page (\`DAR 192\`) you get all its paragraphs; for a paragraph ref (\`GC 326.2\`) you get that one.
3. **Compare the quoted text to the source, character for character** (ignoring only: curly vs straight quotes, en/em-dash style, and an ellipsis \`…\`/\`...\` marking an intentional skip). The quoted words BETWEEN ellipses must appear VERBATIM in the source.
4. Classify:
   - **OK** — verbatim and on the right page → leave it exactly as is.
   - **WRONG PAGE** — text is verbatim but lives on a different page → find the true page (\`egw search "<distinctive phrase>" --book <CODE> --limit 3\`, then lookup), and fix ONLY the refcode in the attribution.
   - **PARAPHRASE** — words differ from the source → REPLACE the quoted text with the true verbatim sentence(s) from the cited page that support the bullet's point, keeping it tight (1-3 sentences). Keep the refcode if the page is right; fix it if not.
   - **UNSUPPORTED/UNRESOLVABLE** — if no page in that work supports the bullet, restore a tight correct quote from the best available page and fix the refcode; only if truly nothing fits, replace the block with the bare pointer \`_(<refcode>)_\` and append \` <!-- TODO: could not verify -->\`.

## Rules
- **Quote VERBATIM. Never paraphrase, smooth, or embellish a quote.** Copy the source's exact words (including its own internal Bible quotations and spellings).
- Preserve the source's KJV citations and capitalization as printed.
- Do NOT touch the bullet's lead text (the bolded Bible reference + explanation) or any Bible reference. Only \`>\` source-quote blocks may change.
- Do NOT touch quotes that are already correct.
- Keep each quote 1-3 sentences (Haskell is suggestive, not exhaustive); trim long pulls with \`…\`.
`;

function agentPrompt(slug) {
  return `You are an ADVERSARIAL VERIFIER for one Bible-study file. Your job is to catch and fix any pioneer/EGW quote that is not verbatim-from-the-cited-page. Repo root: /Users/cvr/Developer/personal/bible-tools.

Target file: \`${SECTIONS_DIR}/${slug}.md\`

${VERIFY_RECIPE}

## Procedure
1. Read \`${SECTIONS_DIR}/${slug}.md\` in full. Count the \`>\` quote blocks (grep \`^    > \`).
2. For EACH quote block, run the verification above against \`egw lookup\`. Be skeptical — assume a quote may be subtly altered until you've matched it to the source text.
3. Fix only the defective ones (wrong page → correct refcode; paraphrase → true verbatim sentence). Leave correct quotes byte-for-byte unchanged.
4. Overwrite the same file with the Write tool (full corrected file).

## Report back (one line)
filename · quote blocks checked · OK · wrong-page fixed · paraphrases replaced · unresolved TODOs.

Work autonomously. Verbatim accuracy is the entire point — a quote that cannot be found on its page must be fixed, not left.`;
}

// ===========================================================================
// Phase 1 — one verifier agent per section.
// ===========================================================================

phase('Verify & Repair');
log(`Adversarially verifying ${SECTIONS.length} sections' quotes against the DB`);

const results = await parallel(
  SECTIONS.map(
    ([slug]) =>
      () =>
        agent(agentPrompt(slug), { label: `verify:${slug}`, phase: 'Verify & Repair' }).then(
          (r) => ({
            slug,
            report: r,
          }),
        ),
  ),
);

const ok = results.filter(Boolean);
log(`${ok.length}/${SECTIONS.length} sections verified`);
for (const r of ok) log(`  ✓ ${r.slug} — ${String(r.report).slice(0, 130)}`);

// ===========================================================================
// Phase 2 — recompile the master from corrected sections (full runs only).
// ===========================================================================

if (!RECOMPILE) {
  log(
    `Subset run (${SECTIONS.length} sections) — skipping recompile. Recompile separately once all sections are verified.`,
  );
  return { verified: ok.map((r) => ({ slug: r.slug, report: r.report })), recompiled: false };
}

phase('Recompile');

const compilePrompt = `Recompile the master file of "Understanding Prophecy — The Full Chain" after each section's quotes were adversarially verified and corrected. Repo root: /Users/cvr/Developer/personal/bible-tools.

The ${SECTIONS.length} section files in \`${SECTIONS_DIR}/\` were just corrected in place. Re-read all of them and rebuild the master at \`${DIR}/understanding-prophecy.md\` (OVERWRITE).

First READ the existing \`${DIR}/understanding-prophecy.md\` to copy its frontmatter, intro, Haskell epigraph, abbreviations, contents, four \`# Part …\` dividers, and colophon UNCHANGED.

Then paste the ${SECTIONS.length} section bodies VERBATIM, in numeric order 1→29, under their part dividers, separated by \`---\`. Order:
${SECTIONS.map(([slug, part], i) => `  ${i + 1}. sections/${slug}.md  [${part}]`).join('\n')}

Do not alter any quote blocks. After writing, verify all 29 \`# N.\` headings and 29 contents anchors are present. Return one line: study count, indented-quote-block count (\`grep -c '^    > '\`), TODO count (\`grep -c 'could not verify'\`), and confirmation written.`;

const compileSummary = await agent(compilePrompt, {
  label: 'recompile:master',
  phase: 'Recompile',
});

log('Verify + recompile complete.');
return { verified: ok.map((r) => ({ slug: r.slug, report: r.report })), compile: compileSummary };
